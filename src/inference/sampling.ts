/**
 * 샘플링 설정.
 *
 * 계약: specs/005-diary-generation/contracts/engine.md 「샘플링」
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **온디바이스와 데스크톱이 공유하는 유일한 자리다**(FR-005·005a).
 *
 * 헌법 원칙 I이 요구한 것은 「동일한 GGUF, 동일한 프롬프트, 동일한 샘플링 파라미터」이며,
 * 실행 위치만 다르고 그 외에 다른 것은 허용하지 않는다. **각 어댑터가 자기 값을 들면 그
 * 요구가 조용히 깨진다** — 한쪽을 고치고 다른 쪽을 잊는 것이 전형적인 실패다.
 *
 * 값을 한 곳에 두면 어긋날 자리가 없다. 001의 `policy.ts`가 원칙 I의 규칙을 한 곳에 모은
 * 것과 같은 구조다.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * **캐릭터별로 갈리지 않는다**(FR-014). 갈리는 순간 성격이 모델이 아니라 파라미터에서
 * 오게 되고, 그것은 관측된 성격이 아니라 우리가 지어낸 성격이다(원칙 III).
 */

/**
 * 생성에 쓰는 값.
 *
 * **`seed`를 두지 않는다.** 같은 하루를 다시 요청하면 다른 일기가 나오는 것이 자연스럽다.
 * 고정하면 「덮어써도 늘 같은 글」이 되어 FR-020a(다시 생성)의 뜻이 사라진다.
 */
export type SamplingSettings = {
  temperature: number;
  top_p: number;
  top_k: number;
  /** 길이 한도 (FR-021a). 없으면 모델이 멈추지 않을 때 기기가 붙잡힌다 */
  n_predict: number;
};

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * **이 값들은 전부 짐작이며 실측이 아니다**(헌법 원칙 V).
 *
 * 온디바이스에서 어떤 값이 좋은지는 관측이 필요한 일이고, **그 관측은 이 저장소의 몫이
 * 아니다**(원칙 IV — 모델 출력을 재는 것은 별도 저장소에서 한다).
 *
 * 근거라고 할 만한 것은 이것뿐이다:
 *  - `temperature` 0.8 — 일기는 사실 나열이 아니라 감상이므로(헌법 「이 앱이 무엇인가」)
 *    지나치게 결정적이면 재미가 없다. 다만 높이면 헌법 원칙 II가 금지한 「단언」이
 *    늘어날 수 있다
 *  - `n_predict` 512 — 하루 일기의 길이로 넉넉하다는 짐작. `n_ctx` 2048과 함께 봐야
 *    하며(engine.md), 프롬프트가 길어지면 둘이 부딪친다
 *
 * **실기기에서 재면 근거가 실측으로 바뀐다**(quickstart D5). 004의
 * `DEFAULT_PHOTO_LIMIT`(200)와 같은 성격의 값이며, 같은 방식으로 다룬다.
 * ─────────────────────────────────────────────────────────────────────────────
 */
export const SAMPLING: SamplingSettings = {
  temperature: 0.8,
  top_p: 0.95,
  top_k: 40,
  n_predict: 512,
};

/**
 * 생성 시간 한도 (FR-021).
 *
 * **짐작이다.** 온디바이스 추론이 얼마나 걸리는지 아직 재지 않았다(quickstart D5).
 * 너무 짧으면 정상 생성이 잘리고, 너무 길면 사용자가 갇힌다.
 *
 * **재는 것과 기록하는 것은 다르다**(FR-011). 한도를 위해 시간을 보는 것은 필요하고,
 * 그 값을 결과에 담거나 저장하는 것이 금지다.
 */
export const GENERATION_TIMEOUT_MS = 180_000;

/**
 * 백그라운드가 조립한 쓰기의 생성 시간 한도 (079, contracts/assembly.md A3).
 *
 * 화면이 조립한 쓰기는 위 180초 그대로다. 어느 조립이 어느 값을 받는지는 `assembly.ts`의
 * `generationTimeoutFor()`가 정한다.
 *
 * **사람이 정한 값이다.** 2026-10-13 SM-S901N의 `dumpsys jobscheduler`가 보인 잡 실행 최소
 * 보장(`runtime_min_guarantee_ms=600000`)에서 왔다 — 그 뒤로는 OS가 언제든 잡을 끊을 수 있다.
 * 한 기기의 값이다. iOS의 백그라운드 시간 예산은 모른다 — iOS 백그라운드 조립에도 같은 값을
 * 쓰는 것은 소유자 결정이다(한도는 속도를 바꾸지 않는 안전장치다).
 *
 * **왜 180초가 아닌가**: 백그라운드 본문은 스레드 2에서 151.0초·174.2초가 걸려 180초에 가깝다
 * (스레드 3 실험은 98.2초·136.1초).
 * 백그라운드에서는 JS 타이머가 억제돼 걸리지 않지만, 그 사이 사용자가 앱을 열면 타이머가 살아나
 * 180초가 지난 실행을 끊는다.
 */
export const BACKGROUND_GENERATION_TIMEOUT_MS = 600_000;

