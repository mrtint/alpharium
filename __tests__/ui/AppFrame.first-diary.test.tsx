/**
 * 111 — `App.tsx`가 첫 일기 흐름을 잇는 모양 (AS0~AS7).
 *
 * 계약: specs/111-first-diary-branch/contracts/first-diary-flow.md 「조립」
 *
 * `App.tsx`는 네이티브 모듈이 많아 jest에서 그리지 않는다 — 소스를 읽는 선례(`AppFrame.firstrun.test.tsx`)를 따른다. 흐름 자체는
 * `first-diary-assembly.test.tsx`가 실제 홈과 묶어 돌린다.
 */

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(__dirname, "../..");
const strip = (source: string) => source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
const APP = strip(readFileSync(join(ROOT, "App.tsx"), "utf8"));
const WIRING = strip(readFileSync(join(ROOT, "src/app/wiring.ts"), "utf8"));

describe("AS0·AS1 — 확인 뒤에만 시작하고 홈이 먼저 그려지지 않는다", () => {
  it("확인 결과의 같은 차례에 흐름으로 넘어간다", () => {
    expect(APP).toMatch(
      /setLivenessOutcome\(outcome\);\s*if \(outcome === "ok"\) firstDiaryLivenessPassed\(\);/,
    );
    expect(APP.match(/firstDiaryLivenessPassed\(\)/g)).toHaveLength(1);
  });

  it("확인 effect가 재료를 읽지 않는다 — 재료는 흐름이 reading에서 읽는다", () => {
    const effect = APP.slice(
      APP.indexOf("const livenessShouldRun"),
      APP.indexOf("useAutoWriteClaim({"),
    );
    expect(effect).not.toMatch(/readFirstMaterial|previewDay/);
  });

  it("reading이면 확인 중 화면을 그린다", () => {
    expect(APP).toMatch(
      /firstRunStage === "naming" \|\| firstRunStage === "liveness" \|\| readingFirstMaterial/,
    );
    expect(APP).toMatch(/welcomePhase: WelcomePhase = readingFirstMaterial\s*\?\s*"checking"/);
  });
});

describe("AS2 — 첫 실행 표식", () => {
  it("흐름에 들어간 표식이 앱 열기 자동 쓰기를 막는다", () => {
    expect(APP).toMatch(/firstRunTried: firstDiary\.entered/);
  });
});

describe("AS3 — 확인창", () => {
  it("asking이면 홈 위에 그리고 두 답이 흐름으로 간다", () => {
    expect(APP).toMatch(
      /firstDiary\.step === "asking" && \(\s*<FirstDiaryConfirmDialog onConfirm=\{firstDiary\.confirm\} onLater=\{firstDiary\.later\} \/>/,
    );
  });
});

describe("AS4 — 되돌림", () => {
  it("되돌리면 확인 결과를 비우고 다시 돌린다", () => {
    expect(APP).toMatch(/onRollBack: rollBackFirstDiary/);
    // 설정을 열어 둔 채 실패해도 확인창이 설정 위에 뜨지 않는다
    expect(APP).toMatch(
      /const rollBackFirstDiary = useCallback\(\(\) => \{\s*goHome\(\);\s*retryLivenessCheck\(\);/,
    );
    expect(APP).toMatch(
      /const retryLivenessCheck = useCallback\(\(\) => \{\s*setLivenessOutcome\(null\);\s*setRetryToken\(\(n\) => n \+ 1\);/,
    );
  });

  it("[그냥 시작하기]는 흐름을 끝낸다", () => {
    const skip = APP.slice(
      APP.indexOf("const onSkipLiveness"),
      APP.indexOf("const onSkipLiveness") + 200,
    );
    expect(skip).toMatch(/firstDiaryLivenessSkipped\(\)/);
  });
});

describe("AS6 — 파이프라인을 직접 돌리는 첫 실행 경로가 없다", () => {
  it("옛 트리거가 사라졌다", () => {
    expect(APP).not.toMatch(
      /triggerFirstRunAutoDiary|shouldAutoGenerate|autoGeneratedToken|autoGenerateTried/,
    );
    expect(WIRING).not.toMatch(/triggerFirstRunAutoDiary/);
    expect(existsSync(join(ROOT, "src/firstrun/auto-diary.ts"))).toBe(false);
  });

  it("쓰기는 홈에 올리는 요청이다", () => {
    expect(APP).toMatch(/setWriteRequest\(\{ id: writeRequestId\.current, day, firstDiary \}\)/);
    expect(APP).toMatch(/onWriteRequestSettled=\{firstDiary\.onWriteSettled\}/);
  });
});

describe("AS7 — 캐릭터 목록을 읽은 뒤에 넘긴다", () => {
  it("첫 일기 요청만 읽기 전에 붙잡는다", () => {
    expect(APP).toMatch(
      /writeRequest=\{writeRequest\?\.firstDiary !== undefined && !selectionRead \? null : writeRequest\}/,
    );
  });
});
