/**
 * 정상 동작 확인 — **순수 판정** (035).
 *
 * 계약: specs/035-model-ready-welcome-naming/contracts/liveness.md L1~L14
 *       spec.md FR-003·FR-003a·FR-003b·FR-004a·FR-010
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **헌법 원칙 IV의 방어선이다.**
 *
 * 모델이 준비됐을 때 「이 캐릭터가 살아 있는가」를 한 번 확인한다. 확인하는 것은
 * **응답이 오는가**뿐이다 — 길이·품질·언어·유사도를 재지 않는다. 재는 순간
 * 그것이 채점이고, 원칙 IV가 2026-08-12 되돌리기의 이유였던 바로 그것이다.
 *
 * **방어가 「안 쓴다」가 아니라 「담을 자리가 없다」이다**:
 *  - `LivenessOutcome`이 **문자열 리터럴 둘**이다(L1·L2). `{ kind, elapsedMs }`
 *    같은 모양이면 시간을 담을 자리가 생긴다 — 005의 `Ending`이 값을 갖지 않고
 *    `RunResult`가 필드 둘뿐인 것과 같은 구조다.
 *  - 실패에 `reason: string`을 두지 않는다. 두면 모델 오류 메시지가 새고, 그
 *    안에 파일 경로가, 경로 안에 자산 키가 있다(원칙 III).
 *
 * **일기 프롬프트와 서로를 모른다**(L7, FR-003b). 이 모듈은 `diary/prompt`를
 * 부르지 않고, `prompt.ts`도 여기를 참조하지 않는다 — 헌법 검사가 양방향으로
 * 막는다. "프롬프트는 `prompt.ts`에만 있다"가 지키려는 것은 **일기 프롬프트의
 * 단일 통과 지점**이며, 확인용 입력은 일기가 아니라 「엔진이 도는가」를 묻는
 * 진단 입력이다.
 *
 * **`judge()`를 재사용하지 않는다**(L5). 「안녕?」의 응답은 `echo`나 `language`로
 * 거부될 수 있는데 **그것은 모델이 죽었다는 뜻이 아니다.** 일기 판정 4갈래를
 * 이 경로에 끌어들이면 갈래의 의미가 흐려진다(005 FR-018b).
 * ─────────────────────────────────────────────────────────────────────────────
 */

import type { Ending } from "../inference/engine-port";

/**
 * 모델에게 보내는 확인용 입력 — **사람이 쓴 고정 상수**(FR-003a).
 *
 * **일기 프롬프트의 어떤 요소도 담지 않는다**(L6): 화자 규칙, 하루의 신호,
 * 캐릭터 이름·호칭 줄, 출력 언어 지시, 제목 지시문. 계약 테스트가 소스를 읽어
 * 이 토큰들의 부재를 잠근다.
 *
 * 짧아야 한다 — 이것은 글을 받으려는 것이 아니라 「대답이 오는가」를 보는 것이다.
 */
export const LIVENESS_INPUT = "안녕?";

/**
 * 확인의 생성 상한(토큰) — **사람이 정한 값이다**(소유자, 2026-10-31 · 측정 아님, 원칙 V). 108 · G2 · F1.
 *
 * 확인이 묻는 것은 「답이 오기 시작했는가」뿐이라 답을 일기 생성 상한(`SAMPLING.n_predict` 512)까지 받을 까닭이
 * 없다. 그렇다고 너무 작으면 첫 토큰 몇 개가 공백·줄바꿈뿐이라 글자 없이 끝나 「비었다」(`failed`)로 오판할 수
 * 있다 — 그래서 「몇 토큰」을 받는다. 16은 그 여유를 두면서 iOS 화면 조각(32, `assembly.ts`)보다 작아 조각 하나로
 * 끝나는 값이다. **이번 호출에만 걸린다**(`RunLimits.maxTokens`) — 일기 본문·제목의 상한은 바뀌지 않는다.
 *
 * 이 값은 판정에 들어가지 않는다(`judgeLiveness()`는 길이를 보지 않는다, L3) — 생성을 일찍 끝낼 뿐이다.
 */
export const LIVENESS_MAX_TOKENS = 16;

/**
 * 확인의 상한 시간 (FR-010) — **사람이 정한 값이다**(원칙 V).
 *
 * 근거(024 §1 실기기 실측, SM-S901N): `quiet` 포그라운드 콜드 `writingMs`가
 * 54.1초, 웜 37.6초였고 그것은 **일기 한 편**(수백 토큰)이다. 확인은 답을
 * `LIVENESS_MAX_TOKENS`(16토큰)에서 끊으므로(108) 생성은 그보다 훨씬 짧다 —
 * 60초는 짧은 답에 넉넉하다. `GENERATION_TIMEOUT_MS`(180초)의 1/3이다. 상한을
 * 줄였어도 이 값은 그대로 둔다 — 줄일 근거가 될 실측이 없다(원칙 V). **한도는 판정이 나는 시각이지 화면이 풀리는 시각이
 * 아니다**(079): 한도에 걸리면 멈춤을 보내고, 그 응답 생성이 실제로 멈춘 뒤에 모델을 내리고
 * 돌아온다. 보통 다음 토큰에서 멈춘다.
 *
 * **`engine.load()`(모델 적재) 시간은 이 한도에 포함하지 않는다**(L14) —
 * `on-device.ts`의 `runWithTimeout()`이 `GENERATION_TIMEOUT_MS`를 다루는 방식과
 * 같다(023에서 확립). 이 값을 화면에 표시하지 않는다.
 */
export const LIVENESS_TIMEOUT_MS = 60_000;

/**
 * 확인 결과. **갈래 둘뿐이고 값을 갖지 않는다**(L1·L2, 원칙 IV).
 *
 * 셋째를 만들지 않는다 — 늘리면 「얼마나 잘 됐나」를 담는 자리가 생기고 그것이
 * 채점이다.
 */
export type LivenessOutcome = "ok" | "failed";

/**
 * 이 캐릭터가 살아 있는가 (FR-003).
 *
 * **순수 함수다**(L4) — 시간을 재지 않는다. 상한은 인자로 받은 `ending`에 이미
 * 반영돼 있다.
 *
 * **보는 것은 셋뿐이다**(L3): 모델을 열었는가, 시간 한도를 넘었는가, 응답이
 * 비었는가. **길이·품질·언어를 보지 않는다** — `text.length > N` 같은 임계값을
 * 두는 순간 그것이 채점이다.
 *
 * **잘린 응답(`length`·`context`·`interrupted`)도 `ok`다** — 005의 `judge()`가
 * 그것을 거부하는 것과 의도적으로 다르다. 여기서 묻는 것은 「좋은 글인가」가
 * 아니라 「대답이 오는가」이고, 잘렸다는 것은 **말을 시작했다**는 뜻이다.
 */
export function judgeLiveness(input: {
  loaded: boolean;
  text: string;
  ending: Ending;
}): LivenessOutcome {
  if (!input.loaded) return "failed";
  if (input.ending.kind === "timeout") return "failed";
  if (input.text.trim() === "") return "failed";
  return "ok";
}
