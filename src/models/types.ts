/**
 * 모델 자산의 모양.
 *
 * 계약: specs/003-character-model-files/contracts/roster.md
 *       specs/003-character-model-files/contracts/readiness.md
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **이 파일은 안쪽 값과 바깥쪽 값을 가른다**(data-model.md 「경계」).
 *
 *  안쪽 — 화면에 절대 나가지 않는다: `ModelAsset`, `AssetKey`, `VerificationVerdict`,
 *         `PausedDownload`
 *  바깥쪽 — 화면이 받아도 된다: `ModelReadiness`, `DownloadProgress`,
 *           `DownloadFailure`, `StorageUsage`
 *
 * **바깥쪽 타입은 안쪽 타입을 필드로 담지 않는다**(FR-003). 담는 순간 화면이 실수할
 * 여지가 생긴다. 조심해서 안 쓰는 것보다 못 쓰게 하는 쪽이 낫다.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * 헌법 원칙 III — 이 기능이 처음으로 캐릭터와 모델 파일을 잇는다. 그래서 핵심 위험이
 * 그 연결의 누출이며, 이 파일이 첫 방어선이다.
 * 헌법 원칙 IV — 속도·점수 필드가 어디에도 없다.
 */

import type { Character } from "../diary/types";

/* ────────────────────────── 안쪽 값 (화면 금지) ────────────────────────── */

/**
 * 기기에서 파일 이름이 되는 값.
 *
 * **캐릭터 식별자와 달라야 한다**(FR-004). 같으면 파일 관리자에서 파일명을 보고
 * 캐릭터를 알 수 있고, 거꾸로 캐릭터로 파일을 찾을 수 있다 — 매핑이 기기에 드러난다.
 *
 * 불투명한 값이며 사람이 읽어 뜻을 알 수 없어야 한다.
 */
export type AssetKey = string;

/**
 * 한 캐릭터가 쓰기 위해 기기에 있어야 하는 것.
 *
 * **이 타입이 `roster.ts` 밖으로 통째로 나가지 않는다**(FR-003). 다른 모듈은 필요한
 * 조각만 인자로 받는다 — 검증 모듈은 "이 경로의 파일이 이 지문과 맞는가"를 묻지 자산을
 * 받지 않는다.
 *
 * **금지**:
 *  - 추론 설정(샘플링 파라미터·컨텍스트 길이)을 담지 않는다(FR-032). 담으면
 *    "받았으니 돌려보자"가 시작된다
 *  - 속도·품질 필드를 담지 않는다(FR-034, 원칙 IV)
 *  - 사람이 읽을 표시 이름·설명을 담지 않는다(FR-004a, FR-005c)
 */
export type ModelAsset = {
  /** 파일 이름이 되는 불투명한 값. 캐릭터 식별자와 다르다 */
  key: AssetKey;
  /** 어디서 받는가. 코드 안쪽 값이며 화면에 나가지 않는다 */
  url: string;
  /** 얼마나 자리를 차지하는가. 공간 판정(FR-019)과 완료 판정(FR-001b)의 근거 */
  expectedBytes: number;
  /** 내용이 온전한지 판정하는 지문 (FR-021, FR-024) */
  md5: string;
};

/**
 * 검증 결과. **기기에 남아 다시 쓰인다**(FR-021b).
 *
 * **`assetKey`를 함께 남기는 이유**(설계 중 발견): 로스터가 바뀌어 캐릭터가 다른 자산을
 * 가리키게 되면, 옛 결과가 새 자산의 것으로 오독된다. 무엇을 검증했는지 적어 두면
 * 어긋남이 드러난다.
 *
 * **시각을 담지 않는다**(원칙 IV). "언제 검증했나"는 필요 없고, 있으면 "얼마나
 * 걸렸나"로 자라기 쉽다.
 *
 * **이것은 "그때 그 파일이 온전했다"는 기록이지 "지금도 거기 있다"는 뜻이
 * 아니다**(FR-021d). 파일의 존재는 물을 때마다 따로 확인한다.
 */
export type VerificationVerdict = {
  /** 무엇을 검증했는가 */
  assetKey: AssetKey;
  /** 검증할 때 본 지문 */
  verifiedMd5: string;
  /** 검증할 때 본 크기. 지금 크기와 견준다 (FR-021e) */
  verifiedBytes: number;
  /** 통과했는가 (FR-021c) */
  passed: boolean;
};

/**
 * 중단된 내려받기. `DownloadTask.savable()`이 돌려주는 값을 **그대로 보관한다**.
 *
 * **우리가 만드는 값이 아니라 보관하는 값이다**(research.md §1). 안을 들여다보거나
 * 고치지 않는다.
 *
 * **여기에 `url`이 들어 있으므로 이것도 안쪽 값이다** — 화면으로 나가지 않는다
 * (설계 중 찾은 누출 경로).
 *
 * **앱이 갑자기 죽으면 이 값이 없을 수 있다.** `savable()`은 `paused` 상태에서만 부를
 * 수 있기 때문이다. 그때도 부분 파일은 남으므로 `partial`이되 이어받기 정보가 없는
 * 경우가 생기며, 지울 수 있어야 한다(FR-029).
 */
export type PausedDownload = {
  assetKey: AssetKey;
  /** expo-file-system의 DownloadPauseState를 직렬화한 것. 안을 해석하지 않는다 */
  state: unknown;
};

/* ───────────────────────── 바깥쪽 값 (화면 허용) ───────────────────────── */

/**
 * 준비 상태. **이 기능이 다른 축에 내주는 핵심 값이다.**
 *
 * 002의 `SignalValue`가 `none`/`unknown`을 가른 것과 같은 구조이며(헌법 원칙 V),
 * 파일이 **부분적으로** 존재하는 상태 때문에 넷이 된다.
 *
 * | 갈래 | 언제 | 사용자가 할 수 있는 것 |
 * | --- | --- | --- |
 * | `ready` | 검증 통과 + 파일이 지금도 있음 | 일기를 쓴다 / 지운다 |
 * | `not-downloaded` | 파일이 없다 | 받기 시작한다 |
 * | `partial` | 일부만 받았다 | **이어받는다** / 지운다 |
 * | `unusable` | 파일은 있는데 쓸 수 없다 | **정리하고 다시 받는다** |
 *
 * **`partial`과 `unusable`을 가르는 이유**(FR-006a): 전자는 이어받으면 되고 후자는
 * 정리하고 다시 받아야 한다. 뭉개면 사용자에게 무엇을 하라고 말할 수 없다.
 *
 * **`reason`에 모델 정보를 담지 않는다**(FR-004). 오류 메시지가 원칙 III의 누출
 * 경로다.
 */
export type ModelReadiness =
  | { kind: "ready" }
  | { kind: "not-downloaded" }
  | { kind: "partial"; reason: string; resumable: boolean }
  | { kind: "unusable"; reason: string };

/**
 * 진행 상태.
 *
 * **불변식**:
 *  1. **캐릭터 단위다**(FR-013a). 파일 이름·파일 개수·바이트 수를 담지 않는다 —
 *     **바이트를 담으면 그것이 곧 모델 크기다**(설계 중 찾은 누출 경로).
 *  2. **시간 관련 필드를 담지 않는다**(원칙 IV, FR-034). `elapsed`나 `bytesPerSecond`를
 *     두면 모델 비교의 시작점이 된다. 남은 시간을 보여주고 싶어도 담지 않는다.
 *  3. **`fraction`이 "모름"일 수 있다**(원칙 V). 서버가 `Content-Length`를 주지 않으면
 *     `totalBytes`가 `-1`이다. 그때 백분율을 지어내지 않는다.
 */
export type DownloadProgress = {
  character: Character;
  /** 0~1, 또는 모르면 null. 지어내지 않는다 */
  fraction: number | null;
};

/**
 * 내려받기가 되지 않은 까닭.
 *
 * **어느 갈래에도 "대신 쓸 자산"이 없다**(FR-035, 원칙 I). 002의 `GenerationFailure`에
 * `text` 필드가 없는 것과 같은 구조 — **타입 수준에서 대체가 불가능해야 한다.**
 *
 * `busy`가 무엇을 받는 중인지 **캐릭터로** 말한다(FR-020) — 사용자가 멈추고 다시
 * 요청할 수 있어야 하므로(FR-020a) 무엇을 멈춰야 하는지 알아야 한다.
 *
 * `insufficient-space`가 **모델 크기를 말하지 않는다**(FR-019a). "이 캐릭터를 두려면
 * 공간이 더 필요하다"이지 "3.2GB가 필요하다"가 아니다.
 */
export type DownloadFailure =
  | { kind: "insufficient-space" }
  | { kind: "network"; reason: string }
  | { kind: "verification-failed" }
  | { kind: "busy"; busyWith: Character };

/**
 * 방금 거부된 요청 (008 FR-001·002).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **일시적이며 기기에 남지 않는다.** 앱을 껐다 켜면 사라지는 것이 옳다 — 「받는 중이라
 * 거부했다」는 그때 참이었던 말이고 지금도 참이라는 보장이 없다. 003이 `running`을
 * 메모리에만 둔 것과 같은 판단이다.
 *
 * **필드가 둘뿐인 것이 방어다**(원칙 IV). 시각(`at`)을 넣으면 「3초 전에 거부됨」을
 * 보이고 싶어지고, 횟수를 넣으면 「3번 거부됨」을 보이고 싶어진다. 담을 자리가 없으면
 * 담을 수 없다.
 *
 * **까닭(`reason`)도 넣지 않는다** — 갈래가 `busy` 하나뿐이므로 담을 것이 없고, 넣으면
 * `insufficient-space`·`network`가 이 통로로 흘러든다(008의 범위 밖이다).
 * ─────────────────────────────────────────────────────────────────────────────
 */
export type DownloadRejection = {
  /** 거부당한 것 — 사용자가 받으려던 캐릭터. 이 줄은 **평소대로** 그려진다(FR-007·010) */
  requested: Character;
  /** 그때 받는 중이던 것 — 사용자가 **멈춰야 할** 캐릭터(FR-002) */
  busyWith: Character;
};

/**
 * 화면이 그릴 것 (008 FR-008·010).
 *
 * 계약: specs/008-download-conflict-feedback/contracts/download-view.md
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **판정은 `download-view.ts`의 순수 함수가 하고 화면은 그리기만 한다.**
 *
 * **불변식**:
 *  1. **`notice`가 하나다**(FR-006). 배열이 아니므로 **쌓일 수 없다** — 여러 번
 *     거부당해도 마지막 것만 남는다.
 *  2. **`active`와 `notice.requested`가 같은 경우가 없다**(FR-010). 받는 중인 것이
 *     동시에 거부당한 것일 수 없다.
 *  3. **시간·속도·바이트가 없다**(FR-016, 원칙 IV). `DownloadProgress`가 담지 않으므로
 *     여기도 담기지 않는다 — 007의 `ActivityIndicator`와 같은 구조적 방어다.
 *  4. **모델 정보가 없다**(FR-004, 원칙 III). 캐릭터 식별자만 흐르며 자산키·주소·크기가
 *     지나갈 통로가 없다.
 * ─────────────────────────────────────────────────────────────────────────────
 */
export type DownloadView = {
  /**
   * 지금 받는 중인 것들. 없으면 빈 배열.
   *
   * **026이 단수 → 복수로 바꿨다** — 서로 다른 캐릭터를 동시에 받을 수 있으므로
   * (026 FR-001·005), 여러 줄에 동시에 진행률·멈추기가 붙는다. 008의 불변식
   * (거부는 이 배열을 절대 건드리지 않는다, `notice.requested`와 겹치지 않는다)은
   * 유지된다. `character`는 배열 안에서 유일하다.
   */
  active: DownloadProgress[];
  /** 보여야 할 거부 안내. 없으면 null. **하나뿐이다**(FR-006) — 026에서도 배열이 아니다 */
  notice: DownloadRejection | null;
};

/**
 * 저장 공간 사용.
 *
 * **캐릭터 단위로 합산한다**(FR-028a). 파일별로 쪼개 보이면 한 캐릭터가 파일 몇 개를
 * 쓰는지 드러나고, 그것이 모델 구성의 정보다. 한 캐릭터가 여러 파일을 가질 수 있는
 * 모양은 열어 두되(FR-033) 밖으로는 하나의 수로 나간다.
 *
 * 부분 파일도 합산한다 — 사용자가 보는 것은 "지금 차지하는 자리"다.
 */
export type StorageUsage = {
  character: Character;
  bytes: number;
};
