/**
 * 캡션 샘플링 설정.
 *
 * 계약: specs/011-photo-vision-summary/contracts/vision-engine.md 「샘플링」
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **★ `src/inference/sampling.ts`를 재사용하지 않는다. 그 이유가 이 파일의 전부다.**
 *
 * 저쪽은 「온디바이스와 데스크톱이 동일한 샘플링 파라미터」를 지키는 자리이며, 헌법
 * 원칙 I이 요구한 것이다. **캡션이 그 값을 같이 쓰면**, 캡션을 위해 `temperature`를
 * 낮추는 순간 **일기 생성의 파라미터가 함께 바뀐다** — 원칙 I의 보증이 조용히 깨지는
 * 경로이며, 고친 사람은 캡션만 고쳤다고 생각한다.
 *
 * **그리고 값이 실제로 정반대여야 한다.**
 *
 * | | 일기 | 캡션 |
 * | --- | ---: | ---: |
 * | `temperature` | 0.8 | **0.1** |
 * | 무엇인가 | 감상 | 관찰 |
 *
 * 일기는 사실 나열이 아니라 감상이므로(헌법 「이 앱이 무엇인가」) 지나치게 결정적이면
 * 재미가 없다. **캡션은 반대다** — 사진에 무엇이 있는지 보는 일이며, 흔들리면 같은
 * 사진에서 다른 답이 나온다.
 *
 * **같은 자리에 둘 수 없는 값이다.**
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * **⚠️ 그래도 원칙 I을 어기지 않는가**: 어기지 않는다. 원칙 I이 요구한 것은 **「엔드유저가
 * 읽는 일기」**가 온디바이스와 데스크톱에서 같은 파라미터로 생성되는 것이다. 캡션은
 * 일기가 아니라 **일기의 입력**이며, 데스크톱 경로가 열릴 때 캡션도 이 값을 쓰면 된다.
 * 그래서 캡션 값도 **한 자리에만 둔다** — 같은 구조를 한 겹 아래에서 반복한다.
 */

export type CaptionSampling = {
  temperature: number;
  /** 캡션 한 줄의 길이 한도 */
  n_predict: number;
};

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * **`temperature` 0.1 — 실측 근거가 있다**(헌법 원칙 V).
 *
 * 옆 저장소(`my-ollama`)가 2026-08-10에 **세 VLM 모두 0.1이 0.7을 이겼다**고 기록했다.
 * SmolVLM 기준 자기일치도 **0.283 → 0.789**, 응답 287ms → 191ms다. 0.7에서 탈락한
 * 캡션은 내용이 틀린 게 아니라 **서술의 장황함이 흔들려** 유사도가 떨어진 것이었다.
 *
 * **`n_predict` 64 — 짐작이다.** 옆 저장소의 실제 캡션이 20~30토큰이었으므로
 * (research.md §5) 2배 남짓의 여유다. **재지 않았다**(quickstart D2·D6).
 *
 * **`top_p`·`top_k`를 두지 않는다** — 정하면 그것이 성능 튜닝이고 원칙 IV의 언저리다.
 * 필요해지면 그때 근거와 함께 더한다.
 * ─────────────────────────────────────────────────────────────────────────────
 */
export const CAPTION_SAMPLING: CaptionSampling = {
  temperature: 0.1,
  n_predict: 64,
};
