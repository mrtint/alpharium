/**
 * 사진 보는 모델의 출처.
 *
 * 계약: specs/011-photo-vision-summary/research.md §6
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **★ `src/models/roster.ts`와 별개의 파일이며 서로 import 하지 않는다.**
 *
 * 003의 로스터는 **캐릭터 → 모델**이고 이 파일은 **사진 보는 모델 하나**다. 합치면
 * 「캐릭터가 사진을 본다」는 잘못된 모양이 코드에 생기고, 003이 지킨 「캐릭터 → 자산은
 * 있고 자산 → 캐릭터는 없다」의 한 방향성이 흐려진다.
 *
 * 이 모델은 **캐릭터와 무관하다**(FR-025). 한 번 받으면 다섯 캐릭터 어느 것으로도
 * 사진을 보며, 그래서 캡션이 캐릭터를 가리지 않는 것이 **규율이 아니라 구조**가 된다
 * (FR-013, SC-001a).
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * **값의 출처 — 옆 저장소의 실측이며 짐작이 아니다**(헌법 원칙 V).
 *
 * `my-ollama`가 2026-08-10에 VLM 셋을 재고 **LFM2.5-VL 450M**을 골랐다. 003의 캐릭터
 * 로스터가 같은 저장소의 URL을 옮겨 온 것과 같은 선례이며, 헌법 원칙 IV가 정한
 * 「별도 저장소에서 수행하고 이 저장소에는 그 결과만 들여온다」를 따른다.
 *
 * **옮긴 것은 「무엇을 쓰는가」뿐이다.** 캡션 품질 점수·자기일치도·두 후보의 비교표는
 * 옮기지 않는다 — 옮기면 이 저장소가 다시 「측정하는 제품」이 된다.
 *
 * **후보: SmolVLM 500M.** 같은 체급이며 동작이 확인됐다. **실행 중 대체가 아니라 사람이
 * 바꿔 넣는 기록이다** — 003 FR-035가 「미리 넣어 둔 모델이나 대체 모델로 채우는 경로를
 * 만들지 않는다」를 못 박았고, 자동으로 옮겨 가면 사용자가 모르는 사이에 다른 것이
 * 사진을 보게 된다.
 *
 * **뺀 것: LFM2.5-VL 1.6B.** 구체성이 가장 높았으나 2.4배 느려 폰 예산 밖이다.
 */

/** 사진 보는 모델의 파일 하나. 003의 `ModelAsset`과 같은 성질이되 별개의 타입이다 */
export type VisionAsset = {
  /**
   * 기기에서 파일 이름이 되는 값.
   *
   * **뜻을 알 수 없는 값을 쓴다**(003 FR-004와 같은 판단). 파일명이 `lfm2.5-vl.gguf`이면
   * 파일 관리자에서 어느 모델인지 드러난다.
   */
  key: string;
  url: string;
  /** 얼마나 자리를 차지하는가. 완료 판정의 근거 */
  expectedBytes: number;
  /** 내용이 온전한지 판정하는 지문 (FR-031) */
  md5: string;
};

/**
 * 사진을 보려면 기기에 있어야 하는 것.
 *
 * **둘 다 있어야 쓸 수 있다**(FR-027). 본체만 있으면 `partial`이며 「쓸 수 있음」이
 * 아니다 — `initMultimodal`이 mmproj 없이는 서지 않는다.
 */
export type VisionAssets = {
  /** 본체 */
  base: VisionAsset;
  /** 멀티모달 프로젝터. `initMultimodal`이 읽는다 */
  projector: VisionAsset;
};

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * **⚠️ 본체와 mmproj의 대소문자가 다르다.**
 *
 * 본체는 `450M`이고 mmproj는 **`450m`**이다. 옆 저장소가 2026-08-10에
 * **「대문자 URL은 404」**임을 확인해 주석으로 남겼다.
 *
 * 놓치면 「내려받기가 안 된다」로 나타나고 **원인이 URL이라는 것을 알기 어렵다.**
 *
 * **`md5`는 아직 비어 있고 그것이 옳은 상태다**(헌법 원칙 V). 003의 로스터가 그랬듯
 * **첫 내려받기에서 받은 파일에서 채록한다**(quickstart D1). 미리 적는 지문은 어디서
 * 왔든 짐작이며, 통과시키려고 그럴듯한 문자열을 넣는 순간 원칙 V가 깨진다.
 * ─────────────────────────────────────────────────────────────────────────────
 */
const ASSETS: VisionAssets = {
  base: {
    key: "v1",
    url: "https://huggingface.co/LiquidAI/LFM2.5-VL-450M-GGUF/resolve/main/LFM2.5-VL-450M-Q8_0.gguf",
    // 실측 (2026-08-22): HTTP 200의 `Content-Length`다. 003이 캐릭터 자산의 크기를
    // 같은 방식으로 얻었다. 짐작이 아니다.
    expectedBytes: 379_219_104,
    md5: "",
  },
  projector: {
    key: "v2",
    // ⚠️ `450m` 소문자다. 대문자는 404다 (2026-08-10 옆 저장소, 2026-08-22 재확인).
    url: "https://huggingface.co/LiquidAI/LFM2.5-VL-450M-GGUF/resolve/main/mmproj-LFM2.5-VL-450m-Q8_0.gguf",
    // 실측 (2026-08-22): HTTP 200의 `Content-Length`.
    expectedBytes: 102_815_168,
    md5: "",
  },
};

/**
 * 사진을 보는 데 필요한 것.
 *
 * **인자가 없다.** 캐릭터를 받지 않는 것이 이 파일의 요점이며, 받게 만들면 캐릭터마다
 * 다른 모델을 줄 수 있게 되어 FR-013이 깨진다.
 */
export function visionAssets(): VisionAssets {
  return ASSETS;
}
