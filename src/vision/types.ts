/**
 * 사진을 읽은 결과의 모양.
 *
 * 계약: specs/011-photo-vision-summary/data-model.md
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **이 파일이 원칙 IV의 첫 방어선이다.**
 *
 * 005의 `RunResult`가 `{ text, ending }` 둘뿐인 것과 같은 판단이며, 여기서는 한 걸음 더
 * 간다 — `PhotoCaption`에 **`confidence`를 두지 않는다.** 두면 「낮은 것은 빼자」가 한
 * 줄로 가능해지고, 그것이 임계값이며 채점 코드의 시작이다.
 *
 * **자리가 없으면 담을 수 없다.**
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * **그리고 원칙 V가 값에서 갈리는 자리다.** 004가 `none`(사진이 0장)과 `unknown`(권한이
 * 없어 못 봤다)을 가른 것이, 여기서는 **「읽지 못했다」와 「사진이 없다」**로 한 겹 위에서
 * 반복된다. 뭉개면 010이 실기기에서 확인한 「없었다 / 모른다」의 성취가 무너진다.
 */

/**
 * 사진 한 장을 읽은 결과.
 *
 * **금지**(FR-032, 원칙 IV): 처리 시간·토큰 수·확신도를 담지 않는다.
 *
 * `text`가 빈 문자열인 값은 만들어지지 않는다 — 비면 실패이며 `captions`에 들어가지
 * 않고 `considered`만 센다(FR-005a).
 */
export type PhotoCaption = {
  /** 어느 사진인가. 004의 `Photo.id`를 그대로 쓴다 */
  photoId: string;
  /**
   * 언제 찍혔는가.
   *
   * **프롬프트가 「하루의 어느 때」를 말하는 근거다**(FR-007b). 고른 다섯 장이 아침에
   * 몰려 있다는 것과 하루에 흩어져 있다는 것은 다른 사실이며, 그 차이가 일기에서
   * 단언과 짐작을 가른다.
   */
  takenAt: Date;
  /** 읽어 낸 문장 */
  text: string;
  /**
   * 캡션에 실제로 쓰인 리사이즈 사본의 경로 (017).
   *
   * **리사이즈가 실행되지 않았거나 원본과 같은 경로였으면(013 C1) 없다** — 그때는
   * 지울 것도 보존할 것도 원본 하나뿐이며 원본은 이 기능의 관리 대상이 아니다.
   * 있으면 그 파일은 캡션이 끝난 시점에 아직 지워지지 않은 상태다 — 최종적으로
   * 지켜지는지 지워지는지는 `pipeline.ts`가 정한다.
   */
  resizedPath?: string;
};

/**
 * 하루의 사진을 읽은 결과.
 *
 * **세 수가 서로 다른 것을 말한다**(FR-006). 004의 `photosWithLocation`/
 * `photosConsidered`가 함께 다니는 것과 같은 구조이며, 같은 이유로 **하나만 꺼내는 편의
 * 함수를 만들지 않는다**(004 FR-027).
 *
 * | 하루 | available | considered | captions.length |
 * | --- | ---: | ---: | ---: |
 * | 사진 3장, 다 읽힘 | 3 | 3 | 3 |
 * | 사진 12장 | 12 | 5 | 5 |
 * | 사진 5장, 1장 실패 | 5 | 5 | 4 |
 * | 사진 5장, 전부 실패 | 5 | 5 | **0** |
 *
 * **마지막 줄이 원칙 V의 자리다.** `captions`가 비었지만 이것은 **「사진이 없다」가
 * 아니다** — 004의 `photos`가 `none`인 것과 완전히 다른 사실이고, 프롬프트가 다르게
 * 적는다.
 */
export type PhotoVision = {
  /** 읽어 낸 것들. 찍힌 시각 순 */
  captions: PhotoCaption[];
  /**
   * 읽으려고 고른 사진의 수.
   *
   * `captions.length`와 다를 수 있다 — 고른 5장 중 2장이 실패하면 3과 5다.
   */
  considered: number;
  /**
   * 그 하루에 있던 사진의 수.
   *
   * `considered`보다 클 수 있다 — 12장 중 5장을 골랐으면 5와 12다.
   * **이것이 「본 것이 전부가 아니다」의 근거다**(FR-012, SC-007).
   *
   * ⚠️ **004가 이미 잘랐으면 이 수도 잘린 수다**(004의 `complete: false`). 그때는 두
   * 한계가 겹치며 프롬프트가 **둘 다** 말해야 한다.
   */
  available: number;
};

/**
 * 사진 읽기가 어떻게 끝났는가.
 *
 * **`seen`과 `no-photos`가 갈리는 것이 핵심이다.** 전자는 「보았다(하나도 못 읽었을 수
 * 있다)」이고 후자는 「볼 것이 없었다」다.
 *
 * **어느 갈래에도 「대신 쓸 것」이 없다**(FR-021, 원칙 I). 003의 `DownloadFailure`,
 * 002의 `GenerationFailure`와 같은 구조 — **타입 수준에서 대체가 불가능해야 한다.**
 */
export type VisionOutcome =
  /** 사진 설정이 「보지 않음」이라 시작하지 않았다 (FR-003) */
  | { kind: "skipped" }
  /**
   * 004가 `none`이거나 `unknown`이라 볼 것이 없었다.
   *
   * **004의 두 갈래를 뭉개지 않는다** — 프롬프트는 004의 `photos` 신호를 여전히 그대로
   * 적는다(「사진: 없었다」 / 「사진: 모른다」). 이 값은 「그래서 캡션 단계를 돌지
   * 않았다」는 뜻일 뿐이다.
   */
  | { kind: "no-photos" }
  /** 읽었다. **전부 실패한 경우도 여기다** — `captions`가 비어 있을 뿐이다 */
  | { kind: "seen"; vision: PhotoVision }
  /** 사진 보는 모델이 기기에 없다 (FR-027) */
  | { kind: "not-ready"; reason: string }
  /** 열지 못했거나 무너졌다 */
  | { kind: "failed"; reason: string }
  /** 사용자가 그만뒀다 (FR-009). **거기까지 읽은 것을 버린다** */
  | { kind: "cancelled" };

/**
 * 얼마나 자세히 볼 것인가.
 *
 * **`VisionSetting`을 그대로 쓰지 않는 까닭**: `none`은 「깊이」가 아니라 「하지 않음」
 * 이다. 포트가 `none`을 받을 수 있으면 「깊이가 none인 캡션」이라는 뜻 없는 상태가
 * 타입에 생긴다 — 002가 `SignalValue`의 `unknown`이 값을 갖지 못하게 한 것과 같은 판단.
 *
 * **둘 다 같은 수의 사진을 본다**(FR-019). 갈리는 것은 한 장을 보는 깊이뿐이다.
 */
export type VisionDepth = "quick" | "detailed";
