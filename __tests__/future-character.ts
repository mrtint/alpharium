/**
 * 「아직 로스터에 없는 둘째 캐릭터」 — 테스트 전용 (037).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **왜 필요한가.**
 *
 * 037로 로스터가 하나가 되며 **캐릭터가 둘 이상일 때만 성립하는 계약**들이 부를
 * 대상을 잃었다. 예를 들어:
 *
 *  - E1(005·018) — "다른 캐릭터를 열면 앞의 것이 먼저 닫힌다"
 *  - E9(018) — "다른 캐릭터가 열려 있으면 `prewarm()`이 조용히 끝난다"
 *  - 026 A13 — "서로 다른 캐릭터는 동시에 받는다"
 *  - 003 — "다른 캐릭터의 파일이 생기지 않는다"
 *
 * 이 계약들은 **없어진 것이 아니라 지금 시험할 대상이 없을 뿐이다.** 헌법 1.6.0이
 * "로스터가 하나라는 것은 완성이 아니라 현재 상태다"를 명시했고, 진입 기준을
 * 통과한 캐릭터는 언제든 들어온다. 그때 이 계약들이 살아 있어야 한다(037 FR-014).
 *
 * **그래서 지우는 대신 「둘째가 있다면」을 이 파일 하나에 모았다.**
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * **이것이 로스터가 아니다.**
 *
 *  - `src/`가 이 파일을 import하지 않는다. 테스트에서만 쓴다.
 *  - 여기에 페르소나·모델 자산·표시 이름을 두지 않는다. 헌법 원칙 III의 통과
 *    지점은 `src/models/roster.ts` 하나이며 이 파일은 그 자리를 대신하지 않는다.
 *  - **`personaOf()`·`assetFor()`에 이 값을 넘기지 않는다** — 로스터 밖 캐릭터에
 *    페르소나·자산이 없는 것이 정상이고, 그것을 확인하는 것은 계약 C3의 몫이다.
 *    여기 쓰는 곳은 "캐릭터 식별자 두 개가 서로 다르다"만 필요한 자리다.
 *
 * **캐릭터가 실제로 늘면 이 파일을 지우고 그 캐릭터로 바꾼다.** 남아 있는 동안은
 * "아직 둘째가 없다"는 사실을 드러내는 장치다(003의 `md5` 빈 문자열이 "아직 재지
 * 않았다"를 드러낸 것과 같은 성격).
 * ─────────────────────────────────────────────────────────────────────────────
 */

